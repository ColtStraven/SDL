//! Markdown rendering. Reports are generated only from [`ResearchData`] and
//! [`CrossReplay`], so every printed figure exists in the JSON datasets.

use crate::engineering::evidence_label;
use crate::measure::Stat;
use crate::research::{ResearchData, TrackResearch};
use crate::survey::CrossReplay;
use std::fmt::Write;

/// Tracks listed individually; the full list is in `research-data.json`.
pub const MD_TRACK_LIMIT: usize = 6;
pub const MD_WEAPON_LIMIT: usize = 10;

pub fn num(v: Option<f64>) -> String {
    v.map(|v| format!("{v}")).unwrap_or_else(|| "unavailable".into())
}

fn stat_row(name: &str, s: &Stat, unit: &str) -> String {
    format!("| {name} | {} | {} | {} | {} | {} | {unit} |\n", num(s.min), num(s.p50), num(s.mean), num(s.p99), num(s.max))
}

fn dist(d: &crate::tracks::Dist, digits: usize) -> String {
    match (d.p50, d.p99) {
        (Some(a), Some(b)) => format!("{a:.digits$} / {b:.digits$}"),
        _ => "unavailable".into(),
    }
}

fn track_rank(t: &TrackResearch) -> (bool, std::cmp::Reverse<u64>) {
    (t.role != "author", std::cmp::Reverse(t.samples))
}

/// `## Strike Master Engineering Findings` and the sections built from it.
fn render_engineering(m: &mut String, d: &ResearchData) {
    let e = &d.engineering;
    let _ = writeln!(m, "## Strike Master Engineering Findings\n");
    let _ = writeln!(m, "Status: {}. Recommendations only: SDL changes nothing in Strike Master or its databases. Full values are under `engineering` in `research-data.json` (schema `{}`).\n", e.status, e.schema);
    if e.findings.is_empty() {
        let _ = writeln!(m, "No engineering findings: this replay holds no author flight evidence.\n");
    }
    for f in &e.findings {
        let _ = writeln!(m, "### {} [{}] {}\n", f.finding_id, f.priority.label(), f.title);
        let _ = writeln!(m, "- **Subsystem:** {}. **Class:** {}, {} confidence, {}.", f.subsystem, evidence_label(f.evidence_class), f.confidence, f.nature.label());
        let _ = writeln!(m, "- **Observation:** {}", f.observation);
        let _ = writeln!(m, "- **Derived analysis:** {}", f.derived_analysis);
        let _ = writeln!(m, "- **Limitations:** {}", if f.limitations.is_empty() { "None beyond the evidence class.".to_string() } else { f.limitations.join(" ") });
        let _ = writeln!(m, "- **Engineering relevance:** {}", f.engineering_relevance);
        if let Some(u) = &f.recommended_follow_up {
            let _ = writeln!(m, "- **Recommended follow-up:** {u}");
        }
        let events: Vec<String> = f.replay_reference.events.iter().map(|s| format!("{} at {} ms", s.subject, s.timestamp_ms.map_or("?".to_string(), |t| t.to_string()))).collect();
        let telemetry = f.telemetry_reference.as_ref().map_or("no 8111 capture".to_string(), |t| format!("8111 capture {}", t.capture_sha256.as_deref().map_or("unavailable", |s| &s[..8.min(s.len())])));
        let _ = writeln!(m, "- **Source:** replay {}, game {}, {telemetry}{}.\n", &f.replay_reference.sha256[..8.min(f.replay_reference.sha256.len())], f.game_version.as_deref().unwrap_or("unavailable"), if events.is_empty() { String::new() } else { format!(", {}", events.join(", ")) });
    }
}

fn render_priorities(m: &mut String, d: &ResearchData) {
    let _ = writeln!(m, "## Recommended research priorities\n");
    let actions: Vec<_> = d.engineering.findings.iter().filter(|f| f.recommended_follow_up.is_some()).collect();
    if actions.is_empty() {
        let _ = writeln!(m, "None from this replay.\n");
        return;
    }
    let _ = writeln!(m, "| Priority | Finding | Follow-up |\n|---|---|---|");
    for f in actions {
        let _ = writeln!(m, "| {} | {} | {} |", f.priority.label(), f.finding_id, f.recommended_follow_up.as_deref().unwrap_or(""));
    }
    m.push('\n');
}

pub fn render(d: &ResearchData) -> String {
    let mut m = String::new();
    let r = &d.replay;
    let _ = writeln!(m, "# SDL Research Report: {}\n", r.file_name);
    let _ = writeln!(m, "Generated by {} {} (schema `{}`). Full data: `research-data.json`.", d.decoder.name, d.decoder.version, d.schema);
    let _ = writeln!(m, "Evidence classes: VERIFIED, REPORTED, DERIVED, EXPERIMENTAL, UNKNOWN. \"unavailable\" means not measured, never zero.\n");

    let _ = writeln!(m, "## Executive summary\n");
    for l in &d.engineering.executive_summary {
        let _ = writeln!(m, "- {l}");
    }
    m.push('\n');

    let _ = writeln!(m, "## 1. Replay identity\n");
    let _ = writeln!(m, "| Field | Value |\n|---|---|");
    let _ = writeln!(m, "| SHA-256 | `{}` |", r.sha256);
    let _ = writeln!(m, "| Size | {} bytes |", r.size_bytes);
    let _ = writeln!(m, "| Decode status | {} |", r.status);
    let _ = writeln!(m, "| Format | {} |", r.format_magic);
    let _ = writeln!(m, "| Game version | {} ({:?}) |", r.game_version, r.game_version_evidence);
    let _ = writeln!(m, "| Session | {} |", r.session_id_hex.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Start (UTC) | {} |", r.start_time_utc.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Mission | {} |", r.mission.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Level | {} |", r.level.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Conditions | {} / {} |", r.environment.as_deref().unwrap_or("unavailable"), r.weather.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Recording | {} |", r.recording.unwrap_or("unavailable"));
    let _ = writeln!(m, "| Timeline span | {} s |\n", num(r.timeline_span_s));

    let _ = writeln!(m, "## 2. Main observations\n");
    if d.findings.is_empty() {
        let _ = writeln!(m, "No author findings: this replay has no attributable author flight.\n");
    } else {
        let _ = writeln!(m, "| ID | Finding | Evidence | Method | Source |\n|---|---|---|---|---|");
        for f in &d.findings {
            let src = f.sources.first().map(|s| format!("{} pkt {}", s.subject, s.packet_index.map(|p| p.to_string()).unwrap_or_else(|| "-".into()))).unwrap_or_else(|| "-".into());
            let _ = writeln!(m, "| {} | {} | {:?} | {} | {src} |", f.id, f.statement, f.evidence, f.method);
        }
        m.push('\n');
    }

    render_engineering(&mut m, d);
    render_priorities(&mut m, d);

    let _ = writeln!(m, "## 3. Recording author\n");
    match &d.author {
        None => {
            let _ = writeln!(m, "unavailable: no state record matched the sync trailer.\n");
        }
        Some(a) => {
            let vehicles = if a.vehicles.is_empty() { "unresolved".to_string() } else { a.vehicles.join(", ") };
            let _ = writeln!(m, "- Vehicle: {vehicles}");
            let _ = writeln!(m, "- Uids: {:?}; tracks: {}", a.uids, a.track_ids.join(", "));
            let _ = writeln!(m, "- Samples: {}; tracked time: {} s", a.samples, a.tracked_seconds);
            let _ = writeln!(m, "- Weapons released (attributed): {}\n", a.weapons_released);
            let author: Vec<&TrackResearch> = d.tracks.iter().filter(|t| t.role == "author").collect();
            let _ = writeln!(m, "| Track | Tracked s | Coverage | Max alt m | Max ground speed m/s | Peak g (1 s) | Max turn deg/s | Best climb m/s (10 s) | Ended |\n|---|---|---|---|---|---|---|---|---|");
            for t in &author {
                let g = t.maneuver.as_ref();
                let ended = match &t.destruction {
                    Some(k) => format!("destroyed by {} ({})", k.killer_vehicle.as_deref().unwrap_or("unknown"), k.weapon.as_deref().unwrap_or("unknown")),
                    None => format!("{} m, {} m/s", num(t.end_altitude_m), num(t.end_speed_mps)),
                };
                let _ = writeln!(
                    m,
                    "| {} | {} | {} | {} | {} | {} | {} | {} | {ended} |",
                    t.track_id,
                    t.duration_s,
                    num(t.sample_coverage),
                    num(t.altitude_m.max),
                    num(t.speed_mps.max),
                    num(g.and_then(|g| g.load_factor_g.max)),
                    num(g.and_then(|g| g.turn_rate_deg_s.max)),
                    num(g.and_then(|g| g.climb_rate_10s_mps.max))
                );
            }
            m.push('\n');
            if let Some(t) = author.iter().max_by_key(|t| t.samples) {
                let _ = writeln!(m, "Longest author track, {} (all tracks in the JSON):\n", t.track_id);
                let _ = writeln!(m, "| Measure | Min | Median | Mean | P99 | Max | Unit |\n|---|---|---|---|---|---|---|");
                m.push_str(&stat_row("Altitude", &t.altitude_m, "m"));
                m.push_str(&stat_row("Ground speed", &t.speed_mps, "m/s"));
                m.push_str(&stat_row("Vertical speed", &t.vertical_speed_mps, "m/s"));
                if let Some(g) = &t.maneuver {
                    m.push_str(&stat_row("Load factor (1 s)", &g.load_factor_g, "g"));
                    m.push_str(&stat_row("Turn rate (1 s)", &g.turn_rate_deg_s, "deg/s"));
                    m.push_str(&stat_row("Longitudinal accel (1 s)", &g.longitudinal_accel_mps2, "m/s2"));
                    m.push_str(&stat_row("Specific excess power (5 s)", &g.specific_excess_power_5s_mps, "m/s"));
                    let _ = writeln!(m, "\nLoad-factor cross-check (velocity vs position second difference), median difference: {} g.", num(g.load_factor_cross_check_g));
                }
                m.push('\n');
            }
            let trs: Vec<_> = author.iter().flat_map(|t| t.transitions.iter().map(move |x| (t, x))).collect();
            if !trs.is_empty() {
                let _ = writeln!(m, "Flight-state transitions (gear bit and engine byte are not independently validated):\n");
                for (t, x) in trs.iter().take(6) {
                    let _ = writeln!(m, "- {} t={} ms: {}{} at {} m, {} m/s", t.track_id, x.timestamp_ms, x.kind, x.detail.as_ref().map(|d| format!(" ({d})")).unwrap_or_default(), x.altitude_m, x.speed_mps);
                }
                if trs.len() > 6 {
                    let _ = writeln!(m, "- plus {} more in the JSON", trs.len() - 6);
                }
                m.push('\n');
            }
        }
    }

    let _ = writeln!(m, "## 4. Aircraft tracks and identity\n");
    let _ = writeln!(m, "{} track segments, {} aircraft units seen. Track ids are provisional; segments are never merged.\n", d.tracks.len(), d.identity.aircraft_units_seen);
    let _ = writeln!(m, "| Identity confidence | Tracks |\n|---|---|");
    for (k, v) in &d.identity.tracks_by_confidence {
        let _ = writeln!(m, "| {k} | {v} |");
    }
    let _ = writeln!(
        m,
        "\nRegistry vs battle log: kills {} match, {} mismatch; damage {} match, {} mismatch.\n",
        d.identity.kill_records_vehicle_match, d.identity.kill_records_vehicle_mismatch, d.identity.damage_records_vehicle_match, d.identity.damage_records_vehicle_mismatch
    );
    let mut ranked: Vec<&TrackResearch> = d.tracks.iter().collect();
    ranked.sort_by_key(|t| track_rank(t));
    let _ = writeln!(m, "| Track | Role | Vehicle | Confidence | Duration s | Samples | Coverage | Max alt m | Max ground speed m/s | Jumps |\n|---|---|---|---|---|---|---|---|---|---|");
    for t in ranked.iter().take(MD_TRACK_LIMIT) {
        let _ = writeln!(
            m,
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            t.track_id,
            t.role,
            t.identity.vehicle.as_deref().unwrap_or("unresolved"),
            t.identity.confidence,
            t.duration_s,
            t.samples,
            num(t.sample_coverage),
            num(t.altitude_m.max),
            num(t.speed_mps.max),
            t.flagged_position_jumps
        );
    }
    if ranked.len() > MD_TRACK_LIMIT {
        let _ = writeln!(m, "\nShowing {MD_TRACK_LIMIT} of {} tracks.", ranked.len());
    }
    m.push('\n');

    let _ = writeln!(m, "## 5. Weapon engagements\n");
    let w = &d.weapons;
    let _ = writeln!(
        m,
        "{} weapons tracked from {} records. Launcher identified by entity id: {}. Author: {}. Named: {} ({} by kill record, {} by type id). Kills linked: {} of {}.\n",
        w.stats.weapons_tracked, w.stats.weapon_records, w.stats.weapons_with_launcher, w.stats.weapons_by_author, w.stats.weapons_named, w.stats.named_by_kill_record, w.stats.named_by_type_id, w.stats.kills_linked_to_weapon, w.stats.kills_seen
    );
    let _ = writeln!(m, "Weapon data limitations are listed under `weapons.limitations` in `research-data.json`. An unknown outcome is not a miss.\n");
    let mut shown: Vec<_> = w.events.iter().filter(|e| e.launcher.is_author || e.weapon_name.is_some()).collect();
    shown.sort_by_key(|e| (!e.launcher.is_author, e.outcome.class == "unknown", e.weapon_name.is_none(), e.trajectory.first_ms));
    if !shown.is_empty() {
        let classes: Vec<String> = w.stats.outcome_classes.iter().map(|(k, v)| format!("{k} {v}")).collect();
        let _ = writeln!(m, "Outcome classes: {}. An unknown outcome is not a miss.\n", classes.join(", "));
        let _ = writeln!(m, "Author and named weapons:\n");
        let _ = writeln!(m, "| Weapon | Type | Name (source) | Launcher | Launch alt m | Launcher speed m/s | ToF s | Max speed m/s | Target (method) | Target distance m | Aspect deg | Closing m/s | Outcome |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|");
        for e in shown.iter().take(MD_WEAPON_LIMIT) {
            let _ = writeln!(
                m,
                "| {} | {} | {} ({}) | {}{} | {} | {} | {} | {} | {} ({}) | {} | {} | {} | {} |",
                e.weapon_id,
                e.template,
                e.weapon_name.as_deref().unwrap_or("unnamed"),
                e.weapon_name_source,
                e.launcher.vehicle.as_deref().unwrap_or("unresolved"),
                if e.launcher.is_author { " (author)" } else { "" },
                num(e.trajectory.launch_altitude_m.map(crate::measure::round3)),
                num(e.launcher.aircraft_speed_mps.map(crate::measure::round3)),
                num(e.trajectory.time_of_flight_s.map(crate::measure::round3)),
                crate::measure::round3(e.trajectory.max_speed_mps),
                e.target.vehicle.as_deref().unwrap_or(if e.target.status == "unavailable" { "unavailable" } else { "unresolved" }),
                e.target.method.as_deref().unwrap_or("-"),
                num(e.geometry.as_ref().map(|g| crate::measure::round3(g.target_distance_m))),
                num(e.geometry.as_ref().and_then(|g| g.target_aspect_deg).map(crate::measure::round3)),
                num(e.geometry.as_ref().and_then(|g| g.closing_speed_mps).map(crate::measure::round3)),
                e.outcome.class
            );
        }
        if shown.len() > MD_WEAPON_LIMIT {
            let _ = writeln!(m, "\nShowing {MD_WEAPON_LIMIT} of {}.", shown.len());
        }
        m.push('\n');
    }
    let _ = writeln!(m, "Battle log: {} kills, {} damage records.\n", d.combat.kills_seen, d.combat.damage_records);

    let _ = writeln!(m, "## 6. Validation\n");
    let k = &d.kinematic_validation;
    let _ = writeln!(m, "| Check (p50 / p99) | Result |\n|---|---|");
    let _ = writeln!(m, "| Author displacement vs velocity, m | {} |", dist(&k.author_displacement_residual_m, 3));
    let _ = writeln!(m, "| Author displacement direction, deg | {} |", dist(&k.author_displacement_direction_error_deg, 3));
    let _ = writeln!(m, "| All aircraft displacement vs velocity, m | {} |", dist(&k.displacement_residual_m, 3));
    let c = &d.cockpit_validation;
    let _ = writeln!(m, "| Altitude vs cockpit, m | {} |", dist(&c.altitude_m.abs_error, 3));
    let _ = writeln!(m, "| Vertical speed vs cockpit, m/s | {} |", dist(&c.vertical_speed_mps.abs_error, 3));
    let _ = writeln!(m, "| Roll vs cockpit, deg | {} |", dist(&c.roll_deg.abs_error, 3));
    let _ = writeln!(m, "| Pitch vs cockpit, deg | {} |", dist(&c.pitch_deg.abs_error, 3));
    let _ = writeln!(m, "| IAS estimate (ground speed, ISA) vs cockpit, m/s | {} |\n", dist(&c.ias_isa_mps.abs_error, 3));

    let _ = writeln!(m, "## 7. Aircraft systems\n");
    let y = &d.systems;
    if y.samples == 0 {
        let _ = writeln!(m, "No author samples.\n");
    } else {
        let _ = writeln!(m, "Replay fields checked against the replay's own cockpit message. See docs/FINDINGS_M7_FLIGHT_SYSTEMS.md for 8111 results.\n");
        let _ = writeln!(m, "| Check | Result | Class |\n|---|---|---|");
        let _ = writeln!(m, "| Author samples (with cockpit) | {} ({}) | VERIFIED |", y.samples, y.samples_with_cockpit);
        let _ = writeln!(m, "| Gear bit vs cockpit gear | {} of {} agree, {} changes | {:?} |", y.gear_vs_cockpit.agree, y.gear_vs_cockpit.n, y.gear_transitions, y.gear_vs_cockpit.evidence);
        let _ = writeln!(m, "| Throttle from engine field vs cockpit (p50 / p99) | {} over {} samples | DERIVED |", dist(&y.throttle_abs_error, 4), y.throttle_boost_samples);
        let _ = writeln!(m, "| Throttle nibble vs cockpit | {} of {} agree | {:?} |", y.throttle_nibble_agree.agree, y.throttle_nibble_agree.n, y.throttle_nibble_agree.evidence);
        let _ = writeln!(m, "| Compass minus (heading + 90), deg (p50 / p99) | {} over {} samples | {:?} |", dist(&y.compass.abs_error_deg, 3), y.compass.n, y.compass.evidence);
        let _ = writeln!(m, "| Cockpit clock rate per replay second | {} over {:.0} s, residual {} s | {:?} |", y.clock.rate.map_or("unavailable".to_string(), |r| format!("{r:.6}")), y.clock.span_s, dist(&y.clock.residual_abs_s, 3), y.clock.evidence);
        let states: Vec<String> = y.engine_states.iter().map(|(k, v)| format!("{k}: {v}")).collect();
        let _ = writeln!(m, "| Engine state byte, samples | {} | EXPERIMENTAL |\n", states.join(", "));
        if !y.load_factor.is_empty() {
            let _ = writeln!(m, "Load factor from position against cockpit id 482, on aircraft that carry it:\n");
            let _ = writeln!(m, "| Vehicle | n | r | Abs err g (p50 / p99) |\n|---|---|---|---|");
            for l in &y.load_factor {
                let _ = writeln!(m, "| {} | {} | {} | {} |", l.vehicle, l.n, l.pearson_r.map_or("unavailable".to_string(), |r| format!("{r:.3}")), dist(&l.abs_error_g, 3));
            }
            m.push('\n');
        }
        if !y.fuel.is_empty() {
            let _ = writeln!(m, "Fuel mass (cockpit id 195, matched to 8111 `Mfuel, kg` on three aircraft):\n");
            let _ = writeln!(m, "| Vehicle | Start kg | End kg | Duration s | kg/s |\n|---|---|---|---|---|");
            for f in y.fuel.iter().take(6) {
                let _ = writeln!(m, "| {} | {:.1} | {:.1} | {:.0} | {:.3} |", f.vehicle, f.start, f.end, f.duration_s, f.rate_per_s);
            }
            m.push('\n');
        }
    }

    let _ = writeln!(m, "## 8. Anomalies\n");
    if d.anomalies.is_empty() {
        let _ = writeln!(m, "None flagged.\n");
    } else {
        let _ = writeln!(m, "| Kind | Count | Evidence | Note |\n|---|---|---|---|");
        for a in &d.anomalies {
            let _ = writeln!(m, "| {} | {} | {:?} | {} |", a.kind, a.count, a.evidence, a.note);
        }
        m.push('\n');
    }

    let _ = writeln!(m, "## 9. Important data limitations\n");
    let md = &d.missing_data;
    let _ = writeln!(m, "{} intervals over 1 s inside tracks, {} s in total.\n", md.intervals_total, md.missing_seconds_total);
    for i in md.intervals.iter().take(5) {
        let _ = writeln!(m, "- {} ({}): {} ms from t={}", i.track_id, i.role, i.gap.duration_ms, i.gap.from_ms);
    }
    let fc = &d.flight_coverage;
    let bits = fc.payload_bits.max(1) as f64;
    let _ = writeln!(
        m,
        "\nAircraft record bits: physical {:.1}%, structural-only {:.1}%, trailer {:.1}%, unparsed {:.1}%.\n",
        100.0 * fc.physically_decoded_bits as f64 / bits,
        100.0 * fc.structural_only_bits as f64 / bits,
        100.0 * fc.trailer_bits as f64 / bits,
        100.0 * fc.unparsed_bits as f64 / bits
    );
    let families: Vec<String> = d.decoded_field_coverage.iter().map(|f| format!("{} ({}, {:?})", f.family, f.status, f.evidence)).collect();
    let _ = writeln!(m, "Data families: {}.\n", families.join("; "));

    let _ = writeln!(m, "## 10. Strike Master proposals\n");
    let _ = writeln!(m, "{} (databases loaded: {}). {} observed shots in `research-data.json`.\n", d.strike_master.database_note, d.strike_master.databases_loaded, d.strike_master.proposals.len());

    let _ = writeln!(m, "## 11. Unresolved questions\n");
    for q in &d.unresolved_questions {
        let _ = writeln!(m, "- {q}");
    }
    m
}

pub fn render_summary(c: &CrossReplay) -> String {
    let mut m = String::new();
    let _ = writeln!(m, "# SDL Cross-Replay Research Summary\n");
    let _ = writeln!(m, "Generated by {} {} (schema `{}`). Full data: `research-summary.json`; per-replay reports in subfolders.\n", c.decoder_name, c.decoder_version, c.schema);
    let _ = writeln!(m, "## 1. Data coverage\n");
    let t = &c.totals;
    let _ = writeln!(m, "| Measure | Value |\n|---|---|");
    let _ = writeln!(m, "| Replays | {} ({} decoded ok) |", t.replays, t.replays_ok);
    let _ = writeln!(m, "| Game versions | {} |", c.game_versions.join(", "));
    let _ = writeln!(m, "| Aircraft samples | {} |", t.flight_samples);
    let _ = writeln!(m, "| Track segments | {} |", t.tracks);
    let _ = writeln!(m, "| Replays with author flight | {} |", t.replays_with_author);
    let _ = writeln!(m, "| Replays with cockpit validation | {} |", t.replays_with_cockpit);
    let _ = writeln!(m, "| Author tracked time | {} s |", t.author_tracked_seconds);
    let _ = writeln!(m, "| Weapons tracked | {} |", t.weapons_tracked);
    let _ = writeln!(m, "| Weapons by author | {} |", t.weapons_by_author);
    let _ = writeln!(m, "| Named weapons | {} |", t.weapons_named);
    let _ = writeln!(m, "| Kills in battle logs | {} |\n", t.kills);

    let _ = writeln!(m, "## 2. Weapon engagement evidence\n");
    let _ = writeln!(m, "| Measure | Value | Evidence |\n|---|---|---|");
    let _ = writeln!(m, "| Launcher identified by entity id | {} of {} | VERIFIED |", t.launchers_verified, t.weapons_tracked);
    let _ = writeln!(m, "| Target from seeker observation | {} | DERIVED |", t.targets_seeker);
    let _ = writeln!(m, "| Target from kill record only | {} | DERIVED |", t.targets_kill_record);
    let _ = writeln!(m, "| Launch geometry available | {} | DERIVED |", t.launch_geometry);
    let _ = writeln!(m, "| Complete records | {} | DERIVED |", t.complete_records);
    let _ = writeln!(m, "| Name hold-out | {} of {} | DERIVED |\n", t.name_holdout_correct, t.name_holdout_attempted);
    let _ = writeln!(m, "| Outcome class | Weapons |\n|---|---|");
    for (k, v) in &t.outcome_classes {
        let _ = writeln!(m, "| {k} | {v} |");
    }
    let _ = writeln!(m, "\nSDL does not classify misses, so `unknown` includes hits, misses and everything else.\n");
    let _ = writeln!(m, "| Target method | Claims on kill-linked weapons | Named the victim |\n|---|---|---|");
    for (k, v) in &t.target_method_checks {
        let _ = writeln!(m, "| {k} | {} | {} |", v.0, v.1);
    }
    m.push('\n');

    let _ = writeln!(m, "## 3. Author aircraft performance by vehicle\n");
    let _ = writeln!(m, "Observed in combat sorties, not controlled tests. Spread is across replays. Maximums are lower bounds on capability. Abrupt velocity changes (collision, break-up, impact candidates) are excluded from g and turn figures.\n");
    let _ = writeln!(m, "| Vehicle | Replays | Tracked s | Max alt m | Max ground speed m/s | Peak g (1 s) | Best climb m/s (10 s) | Best turn deg/s | Speed range across replays |\n|---|---|---|---|---|---|---|---|---|");
    for v in &c.vehicles {
        let _ = writeln!(
            m,
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} to {} |",
            v.vehicle,
            v.replays,
            v.tracked_seconds,
            num(v.max_altitude_m),
            num(v.max_speed_mps),
            num(v.max_load_factor_g),
            num(v.max_climb_10s_mps),
            num(v.max_turn_rate_deg_s),
            num(v.max_speed_low_mps),
            num(v.max_speed_mps)
        );
    }
    m.push('\n');

    let _ = writeln!(m, "## 4. Observed weapon performance\n");
    let _ = writeln!(m, "All named shots from any launcher. Names come from kill records or a shared per-replay type id. Flight figures use shots with at least 5 samples. Launchers are decoded entity ids. Target distance exists only where a tracked target is established. An unknown outcome is not a miss, so these figures do not describe envelope limits or hit probability.\n");
    let _ = writeln!(m, "| Weapon | S57 id | Shots | Confirmed kills | Launchers | ToF s (min/med/max) | Range m (min/med/max) | Max speed m/s | Launch alt m (min/max) | Target at launch m (min/max) |\n|---|---|---|---|---|---|---|---|---|---|");
    for w in &c.weapons {
        let _ = writeln!(
            m,
            "| {} | {} | {} | {} | {} | {} / {} / {} | {} / {} / {} | {} | {} / {} | {} / {} |",
            w.weapon_name,
            w.s57_weapon_id.as_deref().unwrap_or("-"),
            w.shots,
            w.confirmed_kills,
            w.launchers.join(", "),
            num(w.time_of_flight_s.min),
            num(w.time_of_flight_s.p50),
            num(w.time_of_flight_s.max),
            num(w.ground_range_m.min),
            num(w.ground_range_m.p50),
            num(w.ground_range_m.max),
            num(w.max_speed_mps.max),
            num(w.launch_altitude_m.min),
            num(w.launch_altitude_m.max),
            num(w.target_distance_at_launch_m.min),
            num(w.target_distance_at_launch_m.max)
        );
    }
    m.push('\n');

    let _ = writeln!(m, "## 5. Measurement consistency\n");
    let _ = writeln!(m, "Median absolute error per replay (range across replays with enough samples).\n");
    let _ = writeln!(m, "| Check | Replays | Best | Median | Worst |\n|---|---|---|---|---|");
    for x in &c.consistency {
        let _ = writeln!(m, "| {} ({}) | {} | {} | {} | {} |", x.check, x.unit, x.replays, num(x.best), num(x.median), num(x.worst));
    }
    m.push('\n');

    let _ = writeln!(m, "## 6. Outliers and anomalies\n");
    if c.outliers.is_empty() {
        let _ = writeln!(m, "No outliers beyond a robust z-score of 3.5 and a practical size floor.\n");
    } else {
        let _ = writeln!(m, "Robust z-score above 3.5 and above a practical size floor.\n\n| Replay | Measure | Value | Robust z |\n|---|---|---|---|");
        for o in &c.outliers {
            let _ = writeln!(m, "| {} | {} | {} | {} |", o.file_name, o.measure, o.value, o.robust_z);
        }
        m.push('\n');
    }
    let _ = writeln!(m, "| Anomaly | Total |\n|---|---|");
    for (k, v) in &c.anomaly_totals {
        let _ = writeln!(m, "| {k} | {v} |");
    }
    m.push('\n');

    let _ = writeln!(m, "## 7. Replays\n");
    let _ = writeln!(m, "| Replay | Game | Mission | Author vehicle | Tracked s | Max speed | Weapons (author) | Status |\n|---|---|---|---|---|---|---|---|");
    for r in &c.replays {
        let _ = writeln!(
            m,
            "| {} | {} | {} | {} | {} | {} | {} ({}) | {} |",
            r.file_name,
            r.game_version,
            r.mission.as_deref().unwrap_or("unavailable"),
            if r.author_vehicles.is_empty() { "unresolved".to_string() } else { r.author_vehicles.join(", ") },
            num(r.author_tracked_seconds),
            num(r.author_max_speed_mps),
            r.weapons,
            r.weapons_by_author,
            r.status
        );
    }
    m.push('\n');

    let _ = writeln!(m, "## 8. Aircraft systems\n");
    let y = &c.systems;
    let _ = writeln!(m, "Replay fields against the replay's own cockpit message. This table is not independent validation. Real 8111 comparisons are in each flight's validation-report.md.\n");
    let _ = writeln!(m, "| Check | Result |\n|---|---|");
    let _ = writeln!(m, "| Author samples | {} |", y.samples);
    let _ = writeln!(m, "| Gear bit vs cockpit gear | {} of {} agree |", y.gear_agree, y.gear_n);
    let _ = writeln!(m, "| Throttle nibble vs cockpit | {} of {} agree |", y.throttle_nibble_agree, y.throttle_nibble_n);
    let _ = writeln!(m, "| Throttle from engine field | {} samples, worst replay p99 error {} |", y.boost_samples, y.boost_worst_p99.map_or("unavailable".to_string(), |x| format!("{x:.4}")));
    let _ = writeln!(m, "| Compass minus (heading + 90) | {} replays, largest replay median {} deg, worst replay p50 {} deg |", y.compass_replays, y.compass_worst_median_deg.map_or("unavailable".to_string(), |x| format!("{x:.3}")), y.compass_worst_p50_deg.map_or("unavailable".to_string(), |x| format!("{x:.3}")));
    let _ = writeln!(m, "| Cockpit clock rate, replays of 300 s or more | {} replays, {} to {} |\n", y.clock_replays, y.clock_rate_min.map_or("unavailable".to_string(), |x| format!("{x:.6}")), y.clock_rate_max.map_or("unavailable".to_string(), |x| format!("{x:.6}")));
    if !y.load_factor.is_empty() {
        let _ = writeln!(m, "| Vehicle | Samples vs g-meter | r | Abs err g p50 |\n|---|---|---|---|");
        for l in &y.load_factor {
            let _ = writeln!(m, "| {} | {} | {} | {} |", l.vehicle, l.n, l.pearson_r.map_or("unavailable".to_string(), |r| format!("{r:.3}")), l.abs_error_p50_g.map_or("unavailable".to_string(), |x| format!("{x:.3}")));
        }
        m.push('\n');
    }

    let _ = writeln!(m, "## Strike Master Research Opportunities\n");
    let o = &c.research_opportunities;
    let by_priority: Vec<String> = o.findings_by_priority.iter().map(|(k, v)| format!("{k} {v}")).collect();
    let _ = writeln!(m, "Patterns across the corpus, for review. A single sortie is one recording; a pattern needs two or more. {} replays compared with real 8111 data. Per-replay findings: {}.\n", o.replays_compared_with_8111, if by_priority.is_empty() { "none".to_string() } else { by_priority.join(", ") });
    let _ = writeln!(m, "| Id | Area | Priority | Scope | Recordings | Observation | Coverage | Uncertainty | Follow-up |\n|---|---|---|---|---|---|---|---|---|");
    for p in &o.opportunities {
        let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} | {} | {} | {} |", p.opportunity_id, p.area, p.priority.label(), p.scope, p.recordings, p.observation, p.coverage, p.uncertainty, p.recommended_follow_up);
    }
    m.push('\n');
    if !o.fuel.is_empty() {
        let _ = writeln!(m, "Fuel burn in flight stretches of 120 s or more, kg/s:\n");
        let _ = writeln!(m, "| Vehicle | Recordings | Stretches | Seconds | p10 | p50 | p90 | Unit matched to 8111 |\n|---|---|---|---|---|---|---|---|");
        for f in o.fuel.iter().take(12) {
            let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} | {} | {} |", f.vehicle, f.recordings, f.stretches, f.seconds, num(f.burn_kg_s_p10), num(f.burn_kg_s_p50), num(f.burn_kg_s_p90), f.matched_to_8111);
        }
        m.push('\n');
    }
    let _ = writeln!(m, "| Game version | Replays | With author | Gear agreement | Largest compass median, deg |\n|---|---|---|---|---|");
    for g in &o.game_versions {
        let _ = writeln!(m, "| {} | {} | {} | {} | {} |", g.game_version, g.replays, g.replays_with_author, num(g.gear_agreement), num(g.compass_largest_median_deg));
    }
    m.push('\n');

    let _ = writeln!(m, "## 10. Research opportunities and recommended experiments\n");
    for o in &c.recommendations {
        let _ = writeln!(m, "- **{}**: {}", o.title, o.detail);
    }
    m
}

fn opt(x: Option<f64>, digits: usize) -> String {
    x.map_or_else(|| "unavailable".to_string(), |v| format!("{v:.digits$}"))
}

/// Markdown report of one replay-to-telemetry comparison. Raw telemetry stays
/// in the capture folder and full figures in `validation-data.json`.
pub fn render_validation(v: &crate::validate::TelemetryValidation) -> String {
    let mut m = String::new();
    let p = &v.provenance;
    let _ = writeln!(m, "# SDL Telemetry Validation: {}\n", p.replay_file);
    let _ = writeln!(m, "**Status: {}**\n", v.status);
    let _ = writeln!(m, "Generated by sdl-replay-decoder {} (schema `{}`). Full data: `validation-data.json`.\n", p.decoder_version, v.schema);

    let _ = writeln!(m, "## 1. Provenance\n");
    let _ = writeln!(m, "| Item | Value |\n|---|---|");
    let _ = writeln!(m, "| Replay SHA-256 | `{}` |", p.replay_sha256);
    let _ = writeln!(m, "| Game version | {} |", p.game_version.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Replay start (header) | {} |", p.replay_start_utc.as_deref().unwrap_or("unavailable"));
    let _ = writeln!(m, "| Capture | `{}` |", p.capture_dir);
    let _ = writeln!(m, "| Capture SHA-256 | `{}` |", p.capture_sha256);
    let _ = writeln!(m, "| Capture start | {} |", p.capture_started_utc);
    let _ = writeln!(m, "| Recorder | {} on {} |", p.recorder_host, p.recorder_computer.as_deref().unwrap_or("unavailable"));
    let a = &v.association;
    let _ = writeln!(m, "| Association | {} (UTC overlap {:?}, vehicle match {:?}) |", a.class, a.utc_overlap, a.vehicle_match);
    let _ = writeln!(m, "| Replay vehicles | {} |", a.replay_vehicles.join(", "));
    let _ = writeln!(m, "| Capture vehicles | {} |\n", a.capture_vehicles.join(", "));

    let s = &v.sync;
    let _ = writeln!(m, "## 2. Time alignment\n");
    let _ = writeln!(m, "`t_replay = t_capture + offset + drift * (t_capture - {:.1} s)`\n", s.reference_t_s);
    let _ = writeln!(m, "| Item | Value |\n|---|---|");
    let _ = writeln!(m, "| Quality | **{}** |", s.quality);
    let _ = writeln!(m, "| Method | {} |", s.method.unwrap_or("none"));
    let _ = writeln!(m, "| Offset | {} s |", opt(s.offset_s, 3));
    let _ = writeln!(m, "| Uncertainty | {} s |", opt(s.uncertainty_s, 3));
    let _ = writeln!(m, "| Drift | {} ppm (smallest measurable here {} ppm) |", opt(s.drift_ppm, 1), opt(s.drift_resolution_ppm, 1));
    let _ = writeln!(m, "| Discontinuity | {} |", s.discontinuity);
    let _ = writeln!(m, "| Host UTC vs monotonic | {} ppm |\n", opt(v.utc_vs_monotonic_ppm, 1));
    let _ = writeln!(m, "| Method | Status | Offset s | Uncertainty s | n | Note |\n|---|---|---|---|---|---|");
    for r in &s.methods {
        let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} |", r.method, r.status, opt(r.offset_s, 3), opt(r.uncertainty_s, 3), r.n, r.note);
    }
    m.push('\n');
    for l in &s.limitations {
        let _ = writeln!(m, "- {l}");
    }
    if !s.limitations.is_empty() {
        m.push('\n');
    }

    let c = &v.coverage;
    let _ = writeln!(m, "## 3. Measurement coverage\n");
    let _ = writeln!(m, "| Measure | Value |\n|---|---|");
    let _ = writeln!(m, "| Capture span | {:.1} s |", c.capture_span_s);
    let _ = writeln!(m, "| Valid /state readings | {} |", c.valid_state_samples);
    let _ = writeln!(m, "| Valid /indicators readings | {} |", c.valid_indicator_samples);
    let _ = writeln!(m, "| Aligned with replay | {} ({} of readings, {:.1} s) |", c.aligned_samples, opt(c.aligned_fraction, 3), c.aligned_span_s);
    let _ = writeln!(m, "| Telemetry gaps over 1 s | {} (largest {} s) |", c.telemetry_gaps_over_1s, opt(c.largest_telemetry_gap_s, 2));
    let _ = writeln!(m, "| Replay gaps over 1 s | {} |", c.replay_gaps_over_1s);
    let _ = writeln!(m, "| Map position jumps | {} |\n", c.map_position_jumps);
    let _ = writeln!(m, "| Endpoint | Requests | OK | Errors | Interval s (median) | Round trip s (p50 / p99) |\n|---|---|---|---|---|---|");
    for (n, e) in &v.endpoints {
        let _ = writeln!(m, "| {n} | {} | {} | {} | {} | {} / {} |", e.requests, e.ok, e.errors, opt(e.median_interval_s, 3), opt(e.rtt_p50_s, 4), opt(e.rtt_p99_s, 4));
    }
    m.push('\n');

    let _ = writeln!(m, "## 4. Flight-state comparison\n");
    if v.comparisons.is_empty() {
        let _ = writeln!(m, "No comparison was made.\n");
    } else {
        let _ = writeln!(m, "Error is replay minus telemetry. Sync effect is the median error the clock uncertainty alone could cause.\n");
        let _ = writeln!(m, "| Quantity | Replay source | 8111 field | Unit | n | Coverage | Bias | Abs err p50 / p99 | RMSE | r | Sync effect | Class |\n|---|---|---|---|---|---|---|---|---|---|---|---|");
        for r in &v.comparisons {
            let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {:?} |", r.name, r.replay_source, r.telemetry_source, r.unit, r.n, opt(r.coverage, 3), opt(r.bias, 3), dist(&r.abs_error, 3), opt(r.rmse, 3), opt(r.pearson_r, 4), opt(r.sync_sensitivity, 3), r.evidence);
        }
        m.push('\n');
        for r in v.comparisons.iter().filter(|r| r.note.is_some()) {
            let _ = writeln!(m, "- {}: {}", r.name, r.note.as_deref().unwrap_or(""));
        }
        m.push('\n');
    }

    let _ = writeln!(m, "## 5. Altimeter units\n");
    if v.altimeter_scale.is_empty() {
        let _ = writeln!(m, "No altimeter field compared.\n");
    } else {
        let _ = writeln!(m, "The game's foot is 1/3.28 m. The exact foot is 0.3048 m. Each is reported separately.\n");
        let _ = writeln!(m, "| Field | n | r | m per unit | Error as metres | As game foot | As exact foot | Nearest |\n|---|---|---|---|---|---|---|---|");
        for a in &v.altimeter_scale {
            let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} | {} | {} |", a.field, a.n, opt(a.pearson_r, 5), opt(a.metres_per_unit, 6), opt(a.error_as_metres_m, 3), opt(a.error_as_game_foot_m, 3), opt(a.error_as_exact_foot_m, 3), a.nearest);
        }
        m.push('\n');
    }

    if !v.altimeter_by_vehicle.is_empty() {
        let _ = writeln!(m, "From telemetry alone, against `H, m`, for every vehicle in the capture:\n");
        let _ = writeln!(m, "| Vehicle | Field | n | m per unit | r | Nearest |\n|---|---|---|---|---|---|");
        for a in &v.altimeter_by_vehicle {
            let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} |", a.vehicle, a.field, a.n, opt(a.metres_per_unit, 6), opt(a.pearson_r, 6), a.nearest);
        }
        m.push('\n');
    }

    let _ = writeln!(m, "## 6. Horizontal map transform\n");
    match &v.horizontal {
        None => {
            let _ = writeln!(m, "Not fitted.\n");
        }
        Some(h) => {
            let _ = writeln!(m, "Accepted: **{}**. Best: `{}`, RMS {:.1} m over {} positions, next hypothesis {} times worse.\n", h.accepted, h.best, h.best_rms_m, h.n, opt(h.separation, 1));
            let _ = writeln!(m, "Free scale per metre: x {:.3e}, y {:.3e}. From map limits: {:.3e}, {:.3e}. Map direction vs compass: {} deg (p50 / p99).\n", h.free_scale_x.unwrap_or(f64::NAN), h.free_scale_y.unwrap_or(f64::NAN), h.expected_scale_x, h.expected_scale_y, dist(&h.direction_error_deg, 2));
        }
    }

    let _ = writeln!(m, "## 7. Control and engine fields\n");
    if !v.candidate_checks.is_empty() {
        let _ = writeln!(m, "Strongest telemetry partner of each candidate, shown even when weak. A field with one distinct value was not exercised.\n");
        let _ = writeln!(m, "| Candidate | Distinct values | 8111 field | n | r | Scale | Intercept |\n|---|---|---|---|---|---|---|");
        for c in &v.candidate_checks {
            let _ = writeln!(m, "| {} | {} | {} | {} | {} | {} | {} |", c.candidate, c.distinct_values, c.telemetry_field.as_deref().unwrap_or("none"), c.n, opt(c.pearson_r, 3), opt(c.scale, 4), opt(c.intercept, 3));
        }
        m.push('\n');
    }
    if v.field_matches.is_empty() {
        let _ = writeln!(m, "No replay field matched a telemetry field at |r| >= 0.95.\n");
    } else {
        let _ = writeln!(m, "Replay fields with a strong linear relation to a telemetry field, `telemetry = scale * replay + intercept`. A match needs review before it becomes a meaning.\n");
        let _ = writeln!(m, "| Replay field | 8111 field | n | r | Scale | Intercept | Residual RMS |\n|---|---|---|---|---|---|---|");
        for f in v.field_matches.iter().take(30) {
            let _ = writeln!(m, "| {} | {} | {} | {:.4} | {:.5} | {:.4} | {:.4} |", f.replay_field, f.telemetry_field, f.n, f.pearson_r, f.scale, f.intercept, f.residual_rms);
        }
        if v.field_matches.len() > 30 {
            let _ = writeln!(m, "\n{} more in `validation-data.json`.", v.field_matches.len() - 30);
        }
        m.push('\n');
    }

    if !v.marks.is_empty() {
        let _ = writeln!(m, "## 8. Marks\n");
        let _ = writeln!(m, "| Note | Capture s | Replay s | Altitude m | Speed m/s |\n|---|---|---|---|---|");
        for k in &v.marks {
            let _ = writeln!(m, "| {} | {:.2} | {} | {} | {} |", k.note, k.capture_t_s, opt(k.replay_t_s, 2), opt(k.altitude_m, 1), opt(k.speed_mps, 1));
        }
        m.push('\n');
    }

    if !v.fuel_by_vehicle.is_empty() {
        let _ = writeln!(m, "## Fuel use\n");
        let _ = writeln!(m, "From `Mfuel, kg` over the whole capture, combat flight, not a controlled test.\n");
        let _ = writeln!(m, "| Vehicle | Seconds | Burned kg | kg/s | Mean throttle % |\n|---|---|---|---|---|");
        for f in &v.fuel_by_vehicle {
            let _ = writeln!(m, "| {} | {:.0} | {:.0} | {:.3} | {} |", f.vehicle, f.seconds, f.burned_kg, f.mean_kg_per_s, opt(f.mean_throttle_pct, 0));
        }
        m.push('\n');
    }

    let list = |m: &mut String, title: &str, items: &[String]| {
        let _ = writeln!(m, "## {title}\n");
        if items.is_empty() {
            let _ = writeln!(m, "None.");
        }
        for i in items {
            let _ = writeln!(m, "- {i}");
        }
        m.push('\n');
    };
    list(&mut m, "Data gaps", &v.data_gaps);
    list(&mut m, "Verified discoveries", &v.verified_discoveries);
    list(&mut m, "Unresolved technical questions", &v.unresolved);
    list(&mut m, "Potential implications for Strike Master", &v.strike_master_implications);
    m
}
